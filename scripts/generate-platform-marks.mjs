/**
 * Generates local platform-mark assets from the CC0-licensed `simple-icons`
 * package, plus two original geometric glyphs for platforms not covered.
 *
 * Outputs (committed to the repository):
 *   - public/assets/platforms/<slug>.svg
 *   - public/assets/manifest.json           (asset provenance manifest)
 *   - src/components/icons/platform-marks.generated.ts
 *
 * Run: node scripts/generate-platform-marks.mjs
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as simpleIcons from "simple-icons";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const SIMPLE_ICON_CATEGORIES = [
  { slug: "fortnite", exportName: "siFortnite" },
  { slug: "valorant", exportName: "siValorant" },
  { slug: "steam", exportName: "siSteam" },
  { slug: "discord", exportName: "siDiscord" },
  { slug: "tiktok", exportName: "siTiktok" },
  { slug: "instagram", exportName: "siInstagram" },
  { slug: "roblox", exportName: "siRoblox" },
  { slug: "rockstar", exportName: "siRockstargames" },
];

/**
 * Original neutral glyphs drawn for Velour (no source artwork). 24x24 viewBox.
 * - minecraft: isometric block built from three flat faces.
 * - escape-from-tarkov: hexagonal ring with a centered wedge.
 */
const ORIGINAL_GLYPHS = [
  {
    slug: "minecraft",
    title: "Minecraft category glyph (original)",
    path: "M12 1.9 4.1 6.4 12 10.9l7.9-4.5ZM3.3 7.8v9L11.2 21.3v-9ZM20.7 7.8l-7.9 4.5v9l7.9-4.5Z",
  },
  {
    slug: "escape-from-tarkov",
    title: "Escape from Tarkov category glyph (original)",
    path: "M12 1.4 21.4 6.8v10.4L12 22.6 2.6 17.2V6.8Zm0 3.1L5.3 8.3v7.4l6.7 3.8 6.7-3.8V8.3ZM12 8.2l4.4 7.6H7.6Z",
  },
];

const marks = {};
const manifestEntries = [];
const today = new Date().toISOString().slice(0, 10);

for (const { slug, exportName } of SIMPLE_ICON_CATEGORIES) {
  const icon = simpleIcons[exportName];
  if (!icon) throw new Error(`simple-icons is missing ${exportName}`);
  marks[slug] = { title: icon.title, path: icon.path, source: "simple-icons" };
  manifestEntries.push({
    localPath: `public/assets/platforms/${slug}.svg`,
    originalSourceUrl: `https://simpleicons.org/icons/${icon.slug}.svg`,
    sourceName: "Simple Icons (npm: simple-icons)",
    licenseType: "CC0-1.0 (icon set artwork)",
    dateAcquired: today,
    commercialUseStatus:
      "Permitted for the SVG artwork under CC0-1.0. The mark itself remains a trademark of its owner and is used nominatively to identify a marketplace category only.",
    attributionRequirement: "None (CC0-1.0).",
  });
}

for (const glyph of ORIGINAL_GLYPHS) {
  marks[glyph.slug] = {
    title: glyph.title,
    path: glyph.path,
    source: "original",
  };
  manifestEntries.push({
    localPath: `public/assets/platforms/${glyph.slug}.svg`,
    originalSourceUrl: null,
    sourceName: "Original artwork created for Velour",
    licenseType: "Project license (original work)",
    dateAcquired: today,
    commercialUseStatus: "Permitted (original work).",
    attributionRequirement: "None.",
  });
}

const platformsDir = join(root, "public/assets/platforms");
mkdirSync(platformsDir, { recursive: true });
for (const [slug, mark] of Object.entries(marks)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img" aria-label="${mark.title}"><path fill="#cbb3ef" d="${mark.path}"/></svg>\n`;
  writeFileSync(join(platformsDir, `${slug}.svg`), svg);
}

const manifest = {
  note: "Every binary/vector asset stored in public/assets is documented here. All other visuals (gradients, emblem, decorative lines) are original code-drawn SVG/CSS in the repository. Nothing is hotlinked.",
  assets: manifestEntries,
};
writeFileSync(
  join(root, "public/assets/manifest.json"),
  JSON.stringify(manifest, null, 2) + "\n",
);

const tsLines = [
  "// Generated by scripts/generate-platform-marks.mjs — do not edit by hand.",
  "// Sources: simple-icons (CC0-1.0) plus original Velour glyphs.",
  "// Provenance for each mark is documented in public/assets/manifest.json.",
  "",
  "export type PlatformMark = {",
  "  title: string;",
  "  path: string;",
  '  source: "simple-icons" | "original";',
  "};",
  "",
  "export const PLATFORM_MARKS: Record<string, PlatformMark> = {",
  ...Object.entries(marks).map(
    ([slug, mark]) =>
      `  ${JSON.stringify(slug)}: { title: ${JSON.stringify(mark.title)}, path: ${JSON.stringify(mark.path)}, source: ${JSON.stringify(mark.source)} },`,
  ),
  "};",
  "",
];
const iconsDir = join(root, "src/components/icons");
mkdirSync(iconsDir, { recursive: true });
writeFileSync(
  join(iconsDir, "platform-marks.generated.ts"),
  tsLines.join("\n"),
);

console.log(
  `Wrote ${Object.keys(marks).length} platform marks, manifest, and TS module.`,
);
